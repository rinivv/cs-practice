import numpy as np

print("#1")
hours = np.arange(0,22,3)
print("hours", hours)
print("shape", hours.shape)
print("ndim", hours.ndim)
print("size", hours.size)
print("dtype", hours.dtype)

print("line", np.linspace(0,1,5))
print("zeros", np.zeros(6, dtype=int))
print("unknown_table", np.full((2,3), -1))
print("identity", np.eye(3))

print("#2")
print("3й элемент ", hours[2])
print("Последний элемент:", hours[-1])
print("Элементы с 2 по 5:", hours[2:6])
print("Каждый 2й элемент:", hours[::2])
print("В обратном порядке:", hours[::-1])

print("#3")
temperatures = np.array([[12, 14, 13, 15],[11, 13, 16, 17],[10, 12, 15, 18]])
print("Форма:", temperatures.shape)
print("Число измерений:", temperatures.ndim)
print("Число элементов:", temperatures.size)
print("Значение из 2-й строки и 3-го столбца:", temperatures[1, 2])
print("Первая строка:", temperatures[0, :])
print("Последний столбец:", temperatures[:, -1])
print("Первые две строки без первого столбца:\n", temperatures[:2, 1:])
print("Центральный фрагмент 2x2:\n", temperatures[0:2, 1:3])
